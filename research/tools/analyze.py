"""Turn reference and reimplementation runs into research/experiments.csv and a markdown report.

usage: python -I analyze.py OUT_DIR CORPUS_DIR RESEARCH_DIR
Reads OUT_DIR/ref_runs.jsonl and OUT_DIR/re_runs.jsonl; run outputs live in OUT_DIR/<id> (reference)
and OUT_DIR/re_<id> (reimplementation).
"""
import csv
import glob
import itertools
import json
import math
import os
import sys

import numpy as np
from PIL import Image

out_dir, corpus, research = sys.argv[1:4]

SRC = {
    "X-DIM-1": "sq512.png", "X-DIM-2": "wide768.png", "X-DIM-3": "tall512x768.png", "X-DIM-4": "sq1024.png",
    "X-DIM-5": "big2000x1500.png", "X-FMT-1": "fmt_rgba.png", "X-FMT-2": "fmt_gray.png", "X-FMT-3": "fmt_palette.png",
    "X-FMT-4": "wide768.jpg", "X-FMT-5": "fmt_exif6.jpg", "X-FMT-6": "fmt_still.gif", "X-FMT-7": "fmt_upper.PNG",
    "X-INT-1": "wide768.png", "X-INT-3": "wide768.png", "X-TGT-2": "wide768.png", "X-TGT-3": "wide768.png",
    "X-RQ-2": "sq512.png", "X-RQ-3": "sq512.png", "X-RQ-4": "sq512.png", "S-SEED-1": "wide768.png", "S-SEED-2": "wide768.png",
    "X-BAD-a-protected-intensity-LOW-V1.png": "a-protected-intensity-LOW-V1.png",
    "D-GPU-S": "sq512.png", "D-CPU-S": "sq512.png", "D-CPU-REF": "sq512.png",
}
for i in range(1, 6):
    SRC[f"X-REP-{i}"] = "wide768.png"


def load_runs(path):
    runs = {}
    if os.path.exists(path):
        for line in open(path, encoding="utf-8-sig"):
            line = line.strip()
            if line:
                r = json.loads(line)
                runs[r["id"]] = r
    return runs


def rgb_orient(path):
    """Input as the app sees it (orientation applied) for fair diffs."""
    from PIL import ImageOps

    im = Image.open(path)
    try:
        im = ImageOps.exif_transpose(im)
    except Exception:  # noqa: BLE001
        pass
    return np.array(im.convert("RGB")).astype(np.float64)


def metrics(inp, outp):
    x = rgb_orient(inp)
    img = Image.open(outp)
    info = {"out_name": os.path.basename(outp), "out_format": img.format, "out_size": f"{img.size[0]}x{img.size[1]}",
            "out_mode": img.mode, "out_exif": bool(img.getexif())}
    y = np.array(img.convert("RGB")).astype(np.float64)
    if x.shape != y.shape:
        info["size_mismatch"] = True
        return info, None
    d = y - x
    mse = float((d ** 2).mean())
    info.update(max_abs=float(np.abs(d).max()), mae=float(np.abs(d).mean()),
                psnr=float("inf") if mse == 0 else 10 * math.log10(255.0 ** 2 / mse),
                frac_changed=float((np.abs(d).sum(-1) > 0).mean()))
    return info, d


def out_file(prefix, rid):
    files = [f for f in glob.glob(os.path.join(out_dir, prefix + rid, "*")) if "-protected-intensity-" in os.path.basename(f) and not f.endswith(".json")]
    return files[0] if files else None


def cos(a, b):
    a, b = a.ravel(), b.ravel()
    return float(a @ b / (np.linalg.norm(a) * np.linalg.norm(b) + 1e-12))


ref, re_ = load_runs(os.path.join(out_dir, "ref_runs.jsonl")), load_runs(os.path.join(out_dir, "re_runs.jsonl"))
for _rid, _r in load_runs(os.path.join(out_dir, "dev_runs.jsonl")).items():
    (ref if _rid == "D-CPU-REF" else re_)[_rid] = _r
rows, deltas = [], {}
for side, runs, prefix in (("ref", ref, ""), ("re", re_, "re_")):
    for rid, r in runs.items():
        row = {"id": rid, "side": side, "ok": r.get("ok"), "error": (r.get("error") or "")[:90],
               "run_s": round(r.get("run_s", 0) or 0, 1), "peak_vram_mb": round(r.get("peak_vram_mb", 0) or 0),
               "mode": r.get("mode"), "rq": r.get("rq"), "target": r.get("target"), "input": SRC.get(rid, "")}
        of = out_file(prefix, rid) if r.get("ok") else None
        if of and rid in SRC:
            m, d = metrics(os.path.join(corpus, SRC[rid]), of)
            row.update(m)
            deltas[(side, rid)] = d
        rows.append(row)

cols = ["id", "side", "ok", "input", "mode", "rq", "target", "out_name", "out_format", "out_size", "out_mode", "out_exif",
        "max_abs", "mae", "psnr", "frac_changed", "run_s", "peak_vram_mb", "error"]
with open(os.path.join(research, "experiments.csv"), "w", newline="", encoding="utf8") as f:
    w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
    w.writeheader()
    for r in sorted(rows, key=lambda r: (r["id"], r["side"])):
        for k in ("mae", "psnr", "frac_changed", "max_abs"):
            if isinstance(r.get(k), float):
                r[k] = round(r[k], 4)
        w.writerow(r)

lines = ["# Measured results (generated by research/tools/analyze.py)", ""]
lines += ["## Per-run metrics", "", "| id | side | out | size | max err | MAE | PSNR dB | changed | run s | VRAM MB | note |", "|---|---|---|---|---|---|---|---|---|---|---|"]
for r in sorted(rows, key=lambda r: (r["id"], r["side"])):
    if r.get("ok") and "max_abs" in r:
        lines.append(f"| {r['id']} | {r['side']} | {r['out_name']} ({r['out_format']}) | {r['out_size']} | {r['max_abs']:.0f} | {r['mae']:.2f} | {r['psnr']:.2f} | {r['frac_changed']:.3f} | {r['run_s']} | {r['peak_vram_mb']} | |")
    else:
        lines.append(f"| {r['id']} | {r['side']} | - | - | - | - | - | - | {r['run_s']} | {r['peak_vram_mb']} | {r['error']} |")

lines += ["", "## Reference vs reimplementation (same input and parameters)", "",
          "| id | MAE ref | MAE re | PSNR ref | PSNR re | max ref | max re | cosine(perturbations) | out names equal | formats equal |", "|---|---|---|---|---|---|---|---|---|---|"]
for rid in sorted({k[1] for k in deltas}):
    a, b = deltas.get(("ref", rid)), deltas.get(("re", rid))
    ra = next((r for r in rows if r["id"] == rid and r["side"] == "ref" and "mae" in r), None)
    rb = next((r for r in rows if r["id"] == rid and r["side"] == "re" and "mae" in r), None)
    if ra and rb:
        c = cos(a, b) if a is not None and b is not None else float("nan")
        lines.append(f"| {rid} | {ra['mae']:.2f} | {rb['mae']:.2f} | {ra['psnr']:.2f} | {rb['psnr']:.2f} | {ra['max_abs']:.0f} | {rb['max_abs']:.0f} | {c:.3f} | {ra['out_name']==rb['out_name']} | {ra['out_format']==rb['out_format']} |")

for side, label in (("ref", "Reference"), ("re", "Reimplementation")):
    ids = [f"X-REP-{i}" for i in range(1, 6) if (side, f"X-REP-{i}") in deltas]
    if len(ids) >= 2:
        lines += ["", f"## Run-to-run variability, {label} (5 identical unseeded runs)", "", "| pair | cosine of perturbations | mean abs diff of outputs |", "|---|---|---|"]
        cs = []
        for a, b in itertools.combinations(ids, 2):
            c = cos(deltas[(side, a)], deltas[(side, b)])
            md = float(np.abs(deltas[(side, a)] - deltas[(side, b)]).mean())
            cs.append((c, md))
            lines.append(f"| {a} vs {b} | {c:.3f} | {md:.3f} |")
        lines.append(f"\nmean cosine {np.mean([c for c, _ in cs]):.3f}, mean abs diff {np.mean([m for _, m in cs]):.3f}")
if ("re", "S-SEED-1") in deltas and ("re", "S-SEED-2") in deltas:
    lines += ["", "## Reimplementation seeded determinism (seed 123, two runs)", "",
              f"max abs output difference: {float(np.abs(deltas[('re','S-SEED-1')] - deltas[('re','S-SEED-2')]).max()):.1f}"]
for a_, b_, label in ((("re","D-GPU-S"),("re","D-CPU-S"),"reimplementation GPU fp16 vs CPU fp32, same seed 123"),):
    if a_ in deltas and b_ in deltas:
        lines += ["", "## CPU vs GPU", "", f"{label}: cosine of perturbations {cos(deltas[a_], deltas[b_]):.3f}, mean abs output difference {float(np.abs(deltas[a_]-deltas[b_]).mean()):.3f}"]
open(os.path.join(research, "measured-results.md"), "w", encoding="utf8").write("\n".join(lines) + "\n")
print("\n".join(lines))


